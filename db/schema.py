"""Schema management: create the database, tables, and clear agents.

The schema is the classic single-table-inheritance layout:

    agents   -> supertable (shared state)
    humans   -> subtable   (weapon_tier)
    zombies  -> subtable   (strength)

Subtable rows reference ``agents`` through the composite key
``(agent_id, agent_type)`` so the type can never mismatch the supertable.
"""

from __future__ import annotations

import re

import psycopg
from psycopg import sql

from config import simulation_config as cfg
from config.db_config import connect_params

# The position CHECK constraints are named in the DDL so they are easy to spot;
# the startup guard finds them by column name so it also recognises the
# auto-named constraints of older databases.
MAP_COLUMNS = ("x_pos", "y_pos")

AGENTS_DDL = f"""
CREATE TABLE IF NOT EXISTS agents (
    agent_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_type TEXT NOT NULL CHECK (agent_type IN ('human', 'zombie')),
    is_alive   BOOLEAN NOT NULL DEFAULT TRUE,
    x_pos      INTEGER NOT NULL
        CONSTRAINT agents_x_pos_bounds
        CHECK (x_pos BETWEEN {int(cfg.MAP_MIN)} AND {int(cfg.MAP_MAX)}),
    y_pos      INTEGER NOT NULL
        CONSTRAINT agents_y_pos_bounds
        CHECK (y_pos BETWEEN {int(cfg.MAP_MIN)} AND {int(cfg.MAP_MAX)}),
    health     INTEGER NOT NULL,
    speed      INTEGER NOT NULL,
    UNIQUE (agent_id, agent_type)
);
"""

AGENTS_INDEXES = """
CREATE INDEX IF NOT EXISTS idx_agents_position ON agents (x_pos, y_pos);
CREATE INDEX IF NOT EXISTS idx_agents_alive ON agents (is_alive);
"""

HUMANS_DDL = """
CREATE TABLE IF NOT EXISTS humans (
    agent_id    INTEGER NOT NULL,
    agent_type  TEXT NOT NULL DEFAULT 'human' CHECK (agent_type = 'human'),
    weapon_tier INTEGER NOT NULL CHECK (weapon_tier BETWEEN 1 AND 5),
    PRIMARY KEY (agent_id, agent_type),
    FOREIGN KEY (agent_id, agent_type)
        REFERENCES agents (agent_id, agent_type) ON DELETE CASCADE
);
"""

ZOMBIES_DDL = """
CREATE TABLE IF NOT EXISTS zombies (
    agent_id   INTEGER NOT NULL,
    agent_type TEXT NOT NULL DEFAULT 'zombie' CHECK (agent_type = 'zombie'),
    strength   INTEGER NOT NULL CHECK (strength BETWEEN 1 AND 5),
    PRIMARY KEY (agent_id, agent_type),
    FOREIGN KEY (agent_id, agent_type)
        REFERENCES agents (agent_id, agent_type) ON DELETE CASCADE
);
"""


def _server_params(config: dict) -> dict:
    """Connection params for the maintenance database (no target db)."""
    return connect_params(config, dbname="postgres")


def ensure_database(config: dict) -> None:
    """Create the target database if it does not exist."""
    db_name = config["dbname"]
    conn = psycopg.connect(**_server_params(config))
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT 1 FROM pg_catalog.pg_database WHERE datname = %s",
                (db_name,),
            )
            if cur.fetchone() is None:
                cur.execute(
                    sql.SQL("CREATE DATABASE {}").format(sql.Identifier(db_name))
                )
    finally:
        conn.close()


def create_tables(config: dict) -> None:
    """Create the tables if they are missing."""
    conn = psycopg.connect(**connect_params(config))
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute(AGENTS_DDL)
            cur.execute(AGENTS_INDEXES)
            cur.execute(HUMANS_DDL)
            cur.execute(ZOMBIES_DDL)
    finally:
        conn.close()


def drop_tables(config: dict) -> None:
    """Drop all simulation tables."""
    conn = psycopg.connect(**connect_params(config))
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            cur.execute("DROP TABLE IF EXISTS zombies CASCADE;")
            cur.execute("DROP TABLE IF EXISTS humans CASCADE;")
            cur.execute("DROP TABLE IF EXISTS agents CASCADE;")
    finally:
        conn.close()


def tables_exist(config: dict) -> bool:
    conn = psycopg.connect(**connect_params(config))
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT to_regclass('public.agents') IS NOT NULL "
                "AND to_regclass('public.humans') IS NOT NULL "
                "AND to_regclass('public.zombies') IS NOT NULL"
            )
            return bool(cur.fetchone()[0])
    finally:
        conn.close()


def bootstrap(config: dict) -> None:
    """Make sure the database and all tables exist (non-destructive)."""
    ensure_database(config)
    if not tables_exist(config):
        create_tables(config)


def reset_database(config: dict) -> None:
    """Drop every simulation table and recreate an empty schema."""
    ensure_database(config)
    drop_tables(config)
    create_tables(config)


def clear_agents(config: dict) -> int:
    """Delete every agent (and cascade to subtables). Returns rows removed.

    Safe to call when the tables do not exist yet.
    """
    conn = psycopg.connect(**connect_params(config))
    conn.autocommit = True
    try:
        with conn.cursor() as cur:
            if not _agents_table_exists(cur):
                return 0
            cur.execute("SELECT count(*) FROM agents;")
            removed = cur.fetchone()[0]
            cur.execute("TRUNCATE TABLE agents RESTART IDENTITY CASCADE;")
            return removed
    finally:
        conn.close()


def _agents_table_exists(cur) -> bool:
    cur.execute("SELECT to_regclass('public.agents') IS NOT NULL")
    return bool(cur.fetchone()[0])


def _bounds_from_checkdef(definition: str) -> tuple[int, int] | None:
    """Pull the two bounds out of a Postgres ``CHECK`` definition.

    Postgres rewrites ``x_pos BETWEEN -1000 AND 1000`` as
    ``CHECK (((x_pos >= '-1000'::integer) AND (x_pos <= 1000)))``, so the
    numbers are collected and sorted instead of matched positionally.
    """
    values = sorted({int(token) for token in re.findall(r"-?\d+", definition)})
    if len(values) != 2:
        return None
    return values[0], values[1]


def _constraint_bounds(cur, column: str) -> tuple[int, int] | None:
    """Bounds of the CHECK constraint on ``column``, if one can be read."""
    cur.execute(
        "SELECT pg_get_constraintdef(oid) FROM pg_constraint "
        "WHERE conrelid = 'agents'::regclass AND contype = 'c'"
    )
    for (definition,) in cur.fetchall():
        if re.search(rf"\b{column}\b", definition):
            bounds = _bounds_from_checkdef(definition)
            if bounds is not None:
                return bounds
    return None


def map_bounds_mismatch(config: dict) -> str | None:
    """Report a database that still has stale map bounds, else ``None``.

    Read-only on purpose: growing the map changes the schema, so an existing
    database has to be recreated once (menu option 2). Without this check the
    first spawn outside the old box would fail with a bare ``CheckViolation``.
    """
    conn = psycopg.connect(**connect_params(config))
    expected = (int(cfg.MAP_MIN), int(cfg.MAP_MAX))
    stale: list[str] = []
    try:
        with conn.cursor() as cur:
            if not _agents_table_exists(cur):
                return None

            for column in MAP_COLUMNS:
                bounds = _constraint_bounds(cur, column)
                if bounds != expected:
                    shown = f"{bounds[0]}..{bounds[1]}" if bounds else "unknown"
                    stale.append(f"agents.{column} allows {shown}")
    finally:
        conn.close()

    if not stale:
        return None
    return (
        f"The database still has the old map bounds ({'; '.join(stale)}), "
        f"but this build uses {cfg.MAP_MIN}..{cfg.MAP_MAX}."
    )
